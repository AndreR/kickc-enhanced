fixed8_8 fixed_mul(fixed8_8 a, fixed8_8 b) {
    int32_t prod = mul16s(a, b);
    return (fixed8_8)MAKEWORD(BYTE2(prod), BYTE1(prod));
}

ufixed8_8 ufixed_mul(ufixed8_8 a, ufixed8_8 b) {
    uint32_t prod = mul16u(a, b);
    return (ufixed8_8)MAKEWORD(BYTE2(prod), BYTE1(prod));
}

fixed8_8 fixed_div(fixed8_8 a, fixed8_8 b) {
    uint8_t sign = 0;
    if (a < 0) { a = -a; sign ^= 1; }
    if (b < 0) { b = -b; sign ^= 1; }
    uint32_t num = ((uint32_t)a) << 8;
    uint32_t q = div32u16u(num, (uint16_t)b);
    fixed8_8 res = (fixed8_8)q;
    return sign ? -res : res;
}

fixed8_8 fixed_mul_int(fixed8_8 a, int8_t scalar) {
    int32_t prod = mul16s(a, (int16_t)scalar);
    return (fixed8_8)prod;
}

fixed8_8 fixed_abs(fixed8_8 a) {
    return (a < 0) ? -a : a;
}

fixed8_8 fixed_lerp(fixed8_8 a, fixed8_8 b, ufixed8_8 t) {
    fixed8_8 diff = b - a;
    return a + fixed_mul(diff, (fixed8_8)t);
}

fixed8_8 fixed_sin(uint8_t angle) {
    uint8_t lo = FIXED_SIN_TAB_LO[angle];
    uint8_t hi = FIXED_SIN_TAB_HI[angle];
    return (fixed8_8)(((uint16_t)hi << 8) | lo);
}

fixed8_8 fixed_cos(uint8_t angle) {
    return fixed_sin((uint8_t)(angle + 64));
}

uint8_t fixed_atan2(fixed8_8 y, fixed8_8 x) {
    if (x == 0 && y == 0) return 0;
    ufixed8_8 abs_x = (x < 0) ? (ufixed8_8)(-x) : (ufixed8_8)x;
    ufixed8_8 abs_y = (y < 0) ? (ufixed8_8)(-y) : (ufixed8_8)y;
    uint8_t angle;
    if (abs_y <= abs_x) {
        uint8_t ratio = (uint8_t)div16u((uint16_t)(abs_y << 5), abs_x);
        if (ratio > 32) ratio = 32;
        angle = FIXED_ATAN_TAB[ratio];
    } else {
        uint8_t ratio = (uint8_t)div16u((uint16_t)(abs_x << 5), abs_y);
        if (ratio > 32) ratio = 32;
        angle = 64 - FIXED_ATAN_TAB[ratio];
    }
    if (x >= 0) {
        return (y >= 0) ? angle : (uint8_t)(256 - angle);
    } else {
        return (y >= 0) ? (uint8_t)(128 - angle) : (uint8_t)(128 + angle);
    }
}

fixed8_8 fixed_sqrt(fixed8_8 val) {
    if (val <= 0) return 0;
    uint32_t n = ((uint32_t)val) << 8;
    uint32_t res = 0;
    uint32_t bit = 1L << 22;
    while (bit > n) {
        bit >>= 2;
    }
    while (bit != 0) {
        if (n >= res + bit) {
            n -= res + bit;
            res = (res >> 1) + bit;
        } else {
            res >>= 1;
        }
        bit >>= 2;
    }
    return (fixed8_8)res;
}

fixed8_8 fixed_dist(fixed8_8 dx, fixed8_8 dy) {
    fixed8_8 sq_x = fixed_mul(dx, dx);
    fixed8_8 sq_y = fixed_mul(dy, dy);
    return fixed_sqrt(sq_x + sq_y);
}

fixed16_16 fixed16_16_mul(fixed16_16 a, fixed16_16 b) {
    fixed16_16 res;
    int16_t a_hi = a.integer;
    uint16_t a_lo = a.frac;
    int16_t b_hi = b.integer;
    uint16_t b_lo = b.frac;
    int32_t p_hi = (int32_t)MAKELONG((uint16_t)mul16s(a_hi, b_hi), 0);
    int32_t p_mid1 = mul16s(a_hi, (int16_t)b_lo);
    int32_t p_mid2 = mul16s(b_hi, (int16_t)a_lo);
    uint16_t p_lo = WORD1(mul16u(a_lo, b_lo));
    res.val = p_hi + p_mid1 + p_mid2 + (int32_t)p_lo;
    return res;
}

fixed16_16 fixed16_16_div(fixed16_16 a, fixed16_16 b) {
    fixed16_16 res;
    uint8_t sign = 0;
    uint32_t ua = (uint32_t)a.val;
    uint32_t ub = (uint32_t)b.val;
    if (a.val < 0) { ua = (uint32_t)(-a.val); sign ^= 1; }
    if (b.val < 0) { ub = (uint32_t)(-b.val); sign ^= 1; }
    uint32_t q = div32u16u(ua, WORD1(ub));
    int32_t sq = (int32_t)q;
    res.val = sign ? -sq : sq;
    return res;
}
